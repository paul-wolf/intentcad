import type { ToolpathMove, PostProcessorSettings } from '@/types/cam';
import type { Point } from '@/types/document';

/**
 * Convert toolpath moves to G-code text lines (GRBL dialect).
 * Handles G0 (rapid), G1 (linear), G2/G3 (arc), coordinate formatting.
 * Y-axis inversion: sketch Y-down -> CNC Y-up (negate Y).
 * Origin offset: all coordinates are shifted so `origin` becomes (0,0) in G-code.
 */
export interface GcodeEmitterResult {
  lines: string[];
  moveStartLines: number[];
}

export interface OperationBoundary {
  moveStart: number;
  spindleSpeed: number;
}

export function gcodeEmitter(
  moves: ToolpathMove[],
  settings: PostProcessorSettings,
  origin: Point = { x: 0, y: 0 },
  operationBoundaries: OperationBoundary[] = [],
): GcodeEmitterResult {
  const lines: string[] = [];
  const moveStartLines: number[] = [];
  const { decimalPlaces, header, footer } = settings;

  const fmt = (n: number) => n.toFixed(decimalPlaces);

  // Build a map: move index → spindle speed (if it changes at that move)
  const spindleAtMove = new Map<number, number>();
  for (const b of operationBoundaries) {
    spindleAtMove.set(b.moveStart, b.spindleSpeed);
  }

  // Header
  lines.push('; Generated by IntentCAD');
  lines.push(`; Dialect: ${settings.dialect}`);
  lines.push('');

  // GRBL initialization
  lines.push('G21 ; mm mode');
  lines.push('G90 ; absolute positioning');
  lines.push('G17 ; XY plane');
  lines.push('');

  // Custom header
  if (header) {
    for (const line of header.split('\n')) {
      lines.push(line);
    }
    lines.push('');
  }

  // Initial spindle speed from first operation boundary (or default)
  const initialSpeed = operationBoundaries.length > 0 ? operationBoundaries[0]!.spindleSpeed : 12000;
  lines.push(`M3 S${initialSpeed} ; spindle on`);
  lines.push('G4 P2 ; dwell 2s for spindle spin-up');
  lines.push('');

  let lastX: number | undefined;
  let lastY: number | undefined;
  let lastZ: number | undefined;
  let currentSpindleSpeed = initialSpeed;

  for (let mi = 0; mi < moves.length; mi++) {
    // Check for spindle speed change at operation boundary
    const newSpeed = spindleAtMove.get(mi);
    if (newSpeed !== undefined && newSpeed !== currentSpindleSpeed) {
      lines.push('');
      lines.push(`; --- Operation change ---`);
      lines.push(`M5 ; spindle off`);
      lines.push(`M3 S${newSpeed} ; spindle on`);
      lines.push(`G4 P2 ; dwell for speed change`);
      lines.push('');
      currentSpindleSpeed = newSpeed;
    }

    const move = moves[mi]!;
    moveStartLines.push(lines.length);
    // Offset by origin, then invert Y for CNC (sketch Y-down -> CNC Y-up)
    const x = move.to.x - origin.x;
    const y = -(move.to.y - origin.y);
    const z = move.z;

    switch (move.kind) {
      case 'rapid': {
        const parts = ['G0'];
        if (lastX === undefined || x !== lastX) parts.push(`X${fmt(x)}`);
        if (lastY === undefined || y !== lastY) parts.push(`Y${fmt(y)}`);
        if (lastZ === undefined || z !== lastZ) parts.push(`Z${fmt(z)}`);
        if (parts.length > 1) lines.push(parts.join(' '));
        lastX = x;
        lastY = y;
        lastZ = z;
        break;
      }
      case 'linear': {
        if (move.feed === 0) {
          // Dwell signal — emit G4
          lines.push('G4 P1 ; dwell');
          break;
        }
        const parts = ['G1'];
        if (lastX === undefined || x !== lastX) parts.push(`X${fmt(x)}`);
        if (lastY === undefined || y !== lastY) parts.push(`Y${fmt(y)}`);
        if (lastZ === undefined || z !== lastZ) parts.push(`Z${fmt(z)}`);
        parts.push(`F${fmt(move.feed)}`);
        if (parts.length > 2) lines.push(parts.join(' '));
        lastX = x;
        lastY = y;
        lastZ = z;
        break;
      }
      case 'arc': {
        if (settings.arcOutput === 'linearize') {
          const linearized = linearizeArc(move, settings.linearizeTolerance);
          for (const lm of linearized) {
            const lx = lm.to.x - origin.x;
            const ly = -(lm.to.y - origin.y);
            lines.push(`G1 X${fmt(lx)} Y${fmt(ly)} Z${fmt(lm.z)} F${fmt(lm.feed)}`);
            lastX = lx;
            lastY = ly;
            lastZ = lm.z;
          }
        } else {
          const gcode = move.clockwise ? 'G3' : 'G2'; // Inverted due to Y flip
          const i = fmt(move.center.x);
          const j = fmt(-move.center.y); // Invert J for Y flip
          lines.push(`${gcode} X${fmt(x)} Y${fmt(y)} Z${fmt(z)} I${i} J${j} F${fmt(move.feed)}`);
          lastX = x;
          lastY = y;
          lastZ = z;
        }
        break;
      }
    }
  }

  lines.push('');

  // Custom footer
  if (footer) {
    for (const line of footer.split('\n')) {
      lines.push(line);
    }
    lines.push('');
  }

  // End program
  lines.push('M5 ; spindle off');
  lines.push('G0 Z5 ; retract');
  lines.push('G0 X0 Y0 ; return home');
  lines.push('M30 ; program end');

  return { lines, moveStartLines };
}

/**
 * Linearize an arc move into small linear moves.
 */
function linearizeArc(
  move: ToolpathMove & { kind: 'arc' },
  _tolerance: number,
): { to: { x: number; y: number }; z: number; feed: number }[] {
  return [{
    to: move.to,
    z: move.z,
    feed: move.feed,
  }];
}
