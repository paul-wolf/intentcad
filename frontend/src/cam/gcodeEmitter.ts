import type { ToolpathMove, PostProcessorSettings, CamTool } from '@/types/cam';
import type { Point } from '@/types/document';

/**
 * Convert toolpath moves to G-code text lines (GRBL dialect).
 * Handles G0 (rapid), G1 (linear), G2/G3 (arc), G4 (dwell), tool-change pauses,
 * spindle and coolant.
 * Y-axis inversion: sketch Y-down -> CNC Y-up (negate Y).
 * Origin offset: all coordinates are shifted so `origin` becomes (0,0) in G-code.
 */
export interface GcodeEmitterResult {
  lines: string[];
  moveStartLines: number[];
}

export interface OperationBoundary {
  moveStart: number;
  spindleSpeed: number;
  tool?: CamTool;
}

export interface EmitterOptions {
  /** Height to start from, retract to for tool changes, and end at: the job's highest safe Z. */
  safeZ: number;
  floodCoolant: boolean;
  /** Z of the top of the stock (where Z zero is set, normally 0). */
  stockTop?: number;
}

const sameTool = (a: CamTool, b: CamTool) =>
  a.id === b.id && a.diameter === b.diameter && a.type === b.type;

const toolLabel = (t: CamTool) => `${t.name} (${t.diameter} mm ${t.type})`;

export function gcodeEmitter(
  moves: ToolpathMove[],
  settings: PostProcessorSettings,
  origin: Point = { x: 0, y: 0 },
  operationBoundaries: OperationBoundary[] = [],
  options: EmitterOptions = { safeZ: 5, floodCoolant: false },
): GcodeEmitterResult {
  const lines: string[] = [];
  const moveStartLines: number[] = [];
  const { decimalPlaces, header, footer } = settings;
  const { safeZ, floodCoolant } = options;
  const stockTop = options.stockTop ?? 0;

  const fmt = (n: number) => n.toFixed(decimalPlaces);
  const seconds = (s: number) => String(Number(s.toFixed(3)));

  const boundaryAt = new Map<number, OperationBoundary>();
  for (const b of operationBoundaries) boundaryAt.set(b.moveStart, b);

  // Header
  lines.push('; Generated by IntentCAD');
  lines.push(`; Dialect: ${settings.dialect}`);
  const firstTool = operationBoundaries[0]?.tool;
  if (firstTool) lines.push(`; Tool: ${toolLabel(firstTool)}`);
  lines.push(`; Stock top: Z${fmt(stockTop)} (set Z there with the tool touching the top of the stock)`);
  lines.push('');

  // GRBL initialization
  lines.push('G21 ; mm mode');
  lines.push('G90 ; absolute positioning');
  lines.push('G17 ; XY plane');
  lines.push('');

  // Custom header
  if (header) {
    for (const line of header.split('\n')) {
      lines.push(line);
    }
    lines.push('');
  }

  // Up to safe height before anything moves sideways.
  lines.push(`G0 Z${fmt(safeZ)} ; safe height`);

  const initialSpeed = operationBoundaries.length > 0 ? operationBoundaries[0]!.spindleSpeed : 12000;
  const spindleOn = (speed: number) => {
    lines.push(`M3 S${speed} ; spindle on`);
    lines.push('G4 P2 ; dwell 2s for spindle spin-up');
    if (floodCoolant) lines.push('M8 ; flood coolant on');
  };
  spindleOn(initialSpeed);
  lines.push('');

  let lastX: number | undefined;
  let lastY: number | undefined;
  let lastZ: number | undefined = safeZ;
  let currentSpindleSpeed = initialSpeed;
  let currentTool = firstTool;

  const retract = () => {
    if (lastZ === undefined || lastZ < safeZ) {
      lines.push(`G0 Z${fmt(safeZ)}`);
      lastZ = safeZ;
    }
  };

  for (let mi = 0; mi < moves.length; mi++) {
    const boundary = boundaryAt.get(mi);
    if (boundary && mi > 0) {
      const toolChanged = boundary.tool && currentTool && !sameTool(boundary.tool, currentTool);
      if (toolChanged) {
        lines.push('');
        lines.push('; --- Tool change ---');
        retract();
        lines.push('M5 ; spindle off');
        if (floodCoolant) lines.push('M9 ; coolant off');
        lines.push(`; Change to ${toolLabel(boundary.tool!)}, set Z${fmt(stockTop)} at the stock top again, then resume`);
        lines.push('M0 ; pause for tool change');
        // Z was just set with the new tool touching the stock: lift
        // before anything moves, and forget where we were.
        lines.push(`G0 Z${fmt(safeZ)} ; safe height`);
        lastX = undefined;
        lastY = undefined;
        lastZ = safeZ;
        spindleOn(boundary.spindleSpeed);
        lines.push('');
        currentTool = boundary.tool;
        currentSpindleSpeed = boundary.spindleSpeed;
      } else if (boundary.spindleSpeed !== currentSpindleSpeed) {
        lines.push('');
        lines.push('; --- Spindle speed change ---');
        lines.push(`M3 S${boundary.spindleSpeed}`);
        lines.push('G4 P2 ; dwell for speed change');
        lines.push('');
        currentSpindleSpeed = boundary.spindleSpeed;
      }
    }

    const move = moves[mi]!;
    moveStartLines.push(lines.length);
    // Offset by origin, then invert Y for CNC (sketch Y-down -> CNC Y-up)
    const x = move.to.x - origin.x;
    const y = -(move.to.y - origin.y);
    const z = move.z;

    switch (move.kind) {
      case 'rapid': {
        const xy: string[] = [];
        if (lastX === undefined || x !== lastX) xy.push(`X${fmt(x)}`);
        if (lastY === undefined || y !== lastY) xy.push(`Y${fmt(y)}`);
        const zChanges = lastZ === undefined || z !== lastZ;
        if (xy.length > 0 && zChanges) {
          // Never lower Z while moving sideways at rapid: going up, lift first;
          // going down, travel first.
          if (lastZ !== undefined && z < lastZ) {
            lines.push(['G0', ...xy].join(' '));
            lines.push(`G0 Z${fmt(z)}`);
          } else {
            lines.push(`G0 Z${fmt(z)}`);
            lines.push(['G0', ...xy].join(' '));
          }
        } else if (xy.length > 0) {
          lines.push(['G0', ...xy].join(' '));
        } else if (zChanges) {
          lines.push(`G0 Z${fmt(z)}`);
        }
        lastX = x;
        lastY = y;
        lastZ = z;
        break;
      }
      case 'linear': {
        const parts = ['G1'];
        if (lastX === undefined || x !== lastX) parts.push(`X${fmt(x)}`);
        if (lastY === undefined || y !== lastY) parts.push(`Y${fmt(y)}`);
        if (lastZ === undefined || z !== lastZ) parts.push(`Z${fmt(z)}`);
        parts.push(`F${fmt(move.feed)}`);
        if (parts.length > 2) lines.push(parts.join(' '));
        lastX = x;
        lastY = y;
        lastZ = z;
        break;
      }
      case 'dwell': {
        lines.push(`G4 P${seconds(move.seconds)} ; dwell`);
        break;
      }
      case 'arc': {
        // `clockwise` is as seen on screen, which matches the machine seen
        // from above once Y is flipped: clockwise is G2.
        const gcode = move.clockwise ? 'G2' : 'G3';
        const i = fmt(move.center.x);
        const j = fmt(-move.center.y); // Invert J for Y flip
        lines.push(`${gcode} X${fmt(x)} Y${fmt(y)} Z${fmt(z)} I${i} J${j} F${fmt(move.feed)}`);
        lastX = x;
        lastY = y;
        lastZ = z;
        break;
      }
    }
  }

  lines.push('');

  // End program: lift clear first, then stop spindle and coolant.
  retract();
  lines.push('M5 ; spindle off');
  if (floodCoolant) lines.push('M9 ; coolant off');

  // Custom footer
  if (footer) {
    lines.push('');
    for (const line of footer.split('\n')) {
      lines.push(line);
    }
    lines.push('');
  }

  lines.push('G0 X0 Y0 ; return home');
  lines.push('M30 ; program end');

  return { lines, moveStartLines };
}
